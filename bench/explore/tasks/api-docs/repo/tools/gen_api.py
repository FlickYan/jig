"""Writes the API reference: every public function of the package, module by module."""
import importlib
import inspect
import os
import pkgutil
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # the project root


def reference(package_name):
    package = importlib.import_module(package_name)
    lines = [f"<!-- Generated by tools/gen_api.py ({package_name}); run `make docs` instead of editing. -->", "", f"# {package_name} API", ""]
    for info in sorted(pkgutil.iter_modules(package.__path__), key=lambda m: m.name):
        if info.name.startswith("_"):
            continue
        module = importlib.import_module(f"{package_name}.{info.name}")
        functions = [(name, f) for name, f in inspect.getmembers(module, inspect.isfunction) if f.__module__ == module.__name__ and not name.startswith("_")]
        if not functions:
            continue
        lines += [f"## {package_name}.{info.name}", ""]
        for name, function in functions:
            summary = (inspect.getdoc(function) or "").split("\n")[0]
            lines += [f"### `{name}{inspect.signature(function)}`", "", summary or "(undocumented)", ""]
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    sys.stdout.write(reference(sys.argv[1] if len(sys.argv) > 1 else "ledger"))
