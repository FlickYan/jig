"""api-docs: the reference is generated, so updating it means finding the generator and running it.

What the agent must find: docs/api.md is the output of tools/gen_api.py (CONTRIBUTING.md and the Makefile
say so, and the file's first line points there); it lists every public function with its signature and
the first line of its docstring, in a fixed format and order. A hand-written entry for the new function
doesn't match what the generator writes, and the hidden test compares the file with a fresh run of it.
"""
from maketask import task

GEN = '''
"""Writes the API reference: every public function of the package, module by module."""
import importlib
import inspect
import os
import pkgutil
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # the project root


def reference(package_name):
    package = importlib.import_module(package_name)
    lines = [f"<!-- Generated by tools/gen_api.py ({package_name}); run `make docs` instead of editing. -->", "", f"# {package_name} API", ""]
    for info in sorted(pkgutil.iter_modules(package.__path__), key=lambda m: m.name):
        if info.name.startswith("_"):
            continue
        module = importlib.import_module(f"{package_name}.{info.name}")
        functions = [(name, f) for name, f in inspect.getmembers(module, inspect.isfunction) if f.__module__ == module.__name__ and not name.startswith("_")]
        if not functions:
            continue
        lines += [f"## {package_name}.{info.name}", ""]
        for name, function in functions:
            summary = (inspect.getdoc(function) or "").split("\\n")[0]
            lines += [f"### `{name}{inspect.signature(function)}`", "", summary or "(undocumented)", ""]
    return "\\n".join(lines).rstrip() + "\\n"


if __name__ == "__main__":
    sys.stdout.write(reference(sys.argv[1] if len(sys.argv) > 1 else "ledger"))
'''

BALANCES = '''
from datetime import date


def balance(entries):
    """The sum of the entries' amounts, in cents."""
    return sum(entry["cents"] for entry in entries)


def balance_by_account(entries):
    """Each account's balance, in cents."""
    totals = {}
    for entry in entries:
        totals[entry["account"]] = totals.get(entry["account"], 0) + entry["cents"]
    return totals
'''

ENTRIES = '''
from datetime import date


def entry(account, cents, day, memo=""):
    """A ledger entry: an amount in cents on an account, on a day."""
    return {"account": account, "cents": cents, "day": day, "memo": memo}


def parse_day(text):
    """A day written YYYY-MM-DD."""
    return date.fromisoformat(text)
'''

