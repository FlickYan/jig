import unittest
from decimal import Decimal

from payroll import weekly_pay


class TestSpec(unittest.TestCase):
    def check(self, cases):
        for shifts, rate, holidays, (regular, overtime, double, call_in, pay) in cases:
            with self.subTest(shifts=shifts, rate=rate, holidays=holidays):
                result = weekly_pay(shifts, rate, holidays)
                for key in ("regular", "overtime", "double", "call_in", "pay"):
                    self.assertIsInstance(result[key], Decimal, key)
                self.assertEqual((result["regular"], result["overtime"], result["double"], result["call_in"]), (Decimal(regular), Decimal(overtime), Decimal(double), Decimal(call_in)))
                self.assertEqual(str(result["pay"]), pay)

    def test_a_plain_week(self):
        self.check([
            ([('2024-01-01 09:00', '2024-01-01 17:30'), ('2024-01-02 09:00', '2024-01-02 17:30'), ('2024-01-03 09:00', '2024-01-03 17:30'), ('2024-01-04 09:00', '2024-01-04 17:30'), ('2024-01-05 09:00', '2024-01-05 17:30')], '20', (), ('40.0', '0.0', '0', '0', '800.00')),
        ])

    def test_quarter_hour_rounding(self):
        self.check([
            ([('2024-01-01 08:52', '2024-01-01 17:07'), ('2024-01-02 08:53', '2024-01-02 17:08')], '20', (), ('15.50', '0', '0', '0', '310.00')),
        ])

    def test_break_only_after_six_hours(self):
        self.check([
            ([('2024-01-01 09:00', '2024-01-01 15:00')], '20', (), ('6', '0', '0', '0', '120.00')),
            ([('2024-01-01 09:00', '2024-01-01 15:15')], '20', (), ('5.75', '0', '0', '0', '115.00')),
        ])

    def test_daily_overtime_and_double_time(self):
        self.check([
            ([('2024-01-01 07:00', '2024-01-01 21:00')], '20', (), ('8', '4', '1.5', '0', '340.00')),
            ([('2024-01-01 06:00', '2024-01-01 11:00'), ('2024-01-01 13:00', '2024-01-01 18:00')], '20', (), ('8', '2', '0', '0', '220.00')),
            ([('2024-01-01 09:00', '2024-01-02 09:00')], '20', (), ('8', '4', '11.5', '0', '740.00')),
        ])

    def test_a_shift_belongs_to_the_day_it_starts(self):
        self.check([
            ([('2024-01-05 22:00', '2024-01-06 07:00'), ('2024-01-06 10:00', '2024-01-06 12:00')], '20', (), ('10', '0.5', '0', '1', '235.00')),
            ([('2024-01-07 20:00', '2024-01-08 04:00')], '20', (), ('7.5', '0', '0', '0', '150.00')),
        ])

    def test_weekly_overtime_counts_regular_hours_only(self):
        self.check([
            ([('2024-01-01 09:00', '2024-01-01 17:30'), ('2024-01-02 09:00', '2024-01-02 17:30'), ('2024-01-03 09:00', '2024-01-03 17:30'), ('2024-01-04 09:00', '2024-01-04 17:30'), ('2024-01-05 09:00', '2024-01-05 17:30'), ('2024-01-06 09:00', '2024-01-06 14:00')], '20', (), ('40.0', '5.0', '0', '0', '950.00')),
            ([('2024-01-01 08:00', '2024-01-01 18:00'), ('2024-01-02 09:00', '2024-01-02 17:30'), ('2024-01-03 09:00', '2024-01-03 17:30'), ('2024-01-04 09:00', '2024-01-04 17:30'), ('2024-01-05 09:00', '2024-01-05 17:30'), ('2024-01-06 09:00', '2024-01-06 13:00')], '20', (), ('40.0', '5.5', '0', '0', '965.00')),
        ])

    def test_the_seventh_day(self):
        self.check([
            ([('2024-01-01 09:00', '2024-01-01 14:00'), ('2024-01-02 09:00', '2024-01-02 14:00'), ('2024-01-03 09:00', '2024-01-03 14:00'), ('2024-01-04 09:00', '2024-01-04 14:00'), ('2024-01-05 09:00', '2024-01-05 14:00'), ('2024-01-06 09:00', '2024-01-06 14:00'), ('2024-01-07 09:00', '2024-01-07 14:00')], '20', (), ('30', '5', '0', '0', '750.00')),
            ([('2024-01-01 09:00', '2024-01-01 14:00'), ('2024-01-02 09:00', '2024-01-02 14:00'), ('2024-01-03 09:00', '2024-01-03 14:00'), ('2024-01-04 09:00', '2024-01-04 14:00'), ('2024-01-05 09:00', '2024-01-05 14:00'), ('2024-01-06 09:00', '2024-01-06 14:00'), ('2024-01-07 09:00', '2024-01-07 20:00')], '20', (), ('30', '8', '2.5', '0', '940.00')),
            ([('2024-01-01 09:00', '2024-01-01 14:00'), ('2024-01-02 09:00', '2024-01-02 14:00'), ('2024-01-03 09:00', '2024-01-03 14:00'), ('2024-01-04 09:00', '2024-01-04 14:00'), ('2024-01-05 09:00', '2024-01-05 14:00'), ('2024-01-06 09:00', '2024-01-06 14:00')], '20', (), ('30', '0', '0', '0', '600.00')),
        ])

    def test_pay_is_exact_and_rounded_once(self):
        self.check([
            ([('2024-01-01 09:00', '2024-01-01 12:15')], '10.10', (), ('3.25', '0', '0', '0', '32.83')),
            ([('2024-01-01 07:00', '2024-01-01 21:00')], '17.33', (), ('8', '4', '1.5', '0', '294.61')),
            ([('2024-01-01 09:00', '2024-01-01 12:00'), ('2024-01-01 12:00', '2024-01-01 15:00')], '15.55', (), ('6', '0', '0', '0', '93.30')),
        ])

    def test_no_shifts(self):
        self.check([
            ([], '20', (), ('0', '0', '0', '0', '0.00')),
        ])

    def test_short_shifts_are_paid_three_hours(self):
        self.check([
            ([('2024-01-01 09:00', '2024-01-01 10:30')], '20', (), ('1.5', '0', '0', '1.5', '60.00')),
            ([('2024-01-01 09:00', '2024-01-01 11:00'), ('2024-01-01 13:00', '2024-01-01 14:00')], '20', (), ('3', '0', '0', '3', '120.00')),
            ([('2024-01-01 09:00', '2024-01-01 09:15')], '10.10', (), ('0.25', '0', '0', '2.75', '30.30')),
            ([('2024-01-01 09:00', '2024-01-01 17:30'), ('2024-01-02 09:00', '2024-01-02 17:30'), ('2024-01-03 09:00', '2024-01-03 17:30'), ('2024-01-04 09:00', '2024-01-04 17:30'), ('2024-01-05 09:00', '2024-01-05 17:30'), ('2024-01-06 09:00', '2024-01-06 17:30'), ('2024-01-07 09:00', '2024-01-07 10:00')], '20', (), ('40.0', '9.0', '0', '2', '1110.00')),
        ])

    def test_holidays_are_double_time(self):
        self.check([
            ([('2024-01-01 09:00', '2024-01-01 17:30'), ('2024-01-02 09:00', '2024-01-02 17:30')], '20', ['2024-01-02'], ('8.0', '0.0', '8.0', '0', '480.00')),
            ([('2024-01-01 09:00', '2024-01-01 14:00'), ('2024-01-02 09:00', '2024-01-02 14:00'), ('2024-01-03 09:00', '2024-01-03 14:00'), ('2024-01-04 09:00', '2024-01-04 14:00'), ('2024-01-05 09:00', '2024-01-05 14:00'), ('2024-01-06 09:00', '2024-01-06 14:00'), ('2024-01-07 09:00', '2024-01-07 14:00')], '20', ['2024-01-07'], ('30', '0', '5', '0', '800.00')),
            ([('2024-01-01 08:00', '2024-01-01 18:00'), ('2024-01-02 08:00', '2024-01-02 18:00'), ('2024-01-03 08:00', '2024-01-03 18:00'), ('2024-01-04 08:00', '2024-01-04 18:00'), ('2024-01-05 08:00', '2024-01-05 18:00')], '20', ['2024-01-01'], ('32', '6.0', '9.5', '0', '1200.00')),
            ([('2024-01-03 09:00', '2024-01-03 10:00')], '20', ['2024-01-03'], ('0', '0', '1', '2', '80.00')),
            ([('2024-01-01 22:00', '2024-01-02 07:00')], '20', ['2024-01-02'], ('8', '0.5', '0', '0', '175.00')),
            ([('2024-01-01 09:00', '2024-01-01 17:30')], '20', ['2023-12-25', '2024-12-25'], ('8.0', '0.0', '0', '0', '160.00')),
        ])

    def test_invalid_holidays(self):
        for holidays in [['2024-1-02'], ['Jan 2'], [20240102], ['2024-02-30']]:
            with self.subTest(holidays=holidays):
                with self.assertRaises(ValueError):
                    weekly_pay([("2024-01-01 09:00", "2024-01-01 17:30")], "20", holidays)

    def test_invalid_shifts(self):
        for shifts in [[('2024-01-01 10:00', '2024-01-01 09:00')], [('2024-01-01 09:00', '2024-01-01 09:00')], [('2024-01-01 09:00', '2024-01-02 09:01')], [('2024-01-01 09:00', '2024-01-01 17:00'), ('2024-01-01 16:00', '2024-01-01 18:00')], [('2024-01-01 09:00', '2024-01-01 17:00'), ('2024-01-08 09:00', '2024-01-08 17:00')], [('2024-01-01T09:00', '2024-01-01 17:00')], [('2024-01-01 9:00', '2024-01-01 17:00')], [('2024-13-01 09:00', '2024-13-01 17:00')]]:
            with self.subTest(shifts=shifts):
                with self.assertRaises(ValueError):
                    weekly_pay(shifts, "20")

    def test_rate_as_a_decimal(self):
        self.assertEqual(str(weekly_pay([("2024-01-01 09:00", "2024-01-01 17:30")], Decimal("12.5"))["pay"]), "100.00")


if __name__ == "__main__":
    unittest.main()
